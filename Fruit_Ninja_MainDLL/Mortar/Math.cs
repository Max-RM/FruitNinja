		public Random()
		{
			add = 0uL;
			mul = 0uL;
			x = 0uL;
			Seed(3735928559u);
		}

		public Random(uint seed)
		{
			add = 0uL;
			mul = 0uL;
			x = 0uL;
			Seed(seed);
		}

		public void Seed(uint seed)
		{
			x = seed;
			mul = 6726279311198226789uL;
			add = 2531011uL;
		}

		public uint Rand32()
		{
			return Rand32(0u);
		}

		public uint Rand32(uint max)
		{
			x = mul * x + add;
			if (max == 0 || max == uint.MaxValue)
			{
				return (uint)(x >> 32);
			}
			return (uint)((x >> 32) * max >> 32);
		}

		public int Rand32(int max)
		{
			x = mul * x + add;
			if (max == 0 || max == -1)
			{
				return (int)(x >> 32);
			}
			return (int)((long)(x >> 32) * (long)max >>> 32);
		}

		public float RandF(float max)
		{
			float num = Rand32(524287);
			return num / 524287f * max;
		}
	}

