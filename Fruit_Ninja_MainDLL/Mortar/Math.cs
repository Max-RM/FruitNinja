			result.Y = l1.Y;
			return;
		}
		if (l1.X == l2.X)
		{
			result.X = l1.X;
			result.Y = p.Y;
			return;
		}
		float num = (l2.Y - l1.Y) / (l2.X - l1.X);
		float num2 = 0f - 1f / num;
		result.X = ((0f - num2) * p.X + p.Y - l1.Y + num * l1.X) / (num - num2);
